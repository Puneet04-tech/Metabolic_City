/**
 * Minimal class name combiner.
 *
 * Accepts strings, numbers, arrays and objects. Deliberately tiny — there is
 * no variant library in this project; variants are expressed with
 * `data-variant` / `data-size` attributes on the element itself.
 */
export function cn(...inputs) {
  const classes = [];

  for (const input of inputs) {
    if (!input) continue;

    if (typeof input === 'string' || typeof input === 'number') {
      classes.push(String(input));
    } else if (Array.isArray(input)) {
      const nested = cn(...input);
      if (nested) classes.push(nested);
    } else if (typeof input === 'object') {
      for (const [key, value] of Object.entries(input)) {
        if (value) classes.push(key);
      }
    }
  }

  return classes.join(' ');
}
